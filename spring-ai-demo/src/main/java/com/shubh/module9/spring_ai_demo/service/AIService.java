package com.shubh.module9.spring_ai_demo.service;

import lombok.AccessLevel;
import lombok.RequiredArgsConstructor;
import lombok.experimental.FieldDefaults;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

@FieldDefaults(makeFinal = true, level = AccessLevel.PRIVATE)
@RequiredArgsConstructor
@Service
public class AIService {

    /**
     * ChatClient is the primary abstraction provided by Spring AI for
     * interacting with Large Language Models (LLMs).
     *
     * It acts as a high-level client responsible for:
     *
     *      Application
     *            │
     *            ▼
     *      ChatClient
     *            │
     *            ▼
     *      ChatModel
     *            │
     *            ▼
     *      AI Provider
     *      (Ollama / OpenAI / Gemini / Anthropic ...)
     *
     * Since only a single ChatClient bean currently exists in the Spring
     * context, constructor injection generated by Lombok's
     * @RequiredArgsConstructor works without any additional configuration.
     */
    ChatClient chatClient;


    /**
     * =========================================================================
     * FUTURE (Multiple AI Providers)
     * =========================================================================
     *
     * If multiple ChatClient beans are registered, for example:
     *
     *      ChatClient ("ollama")
     *      ChatClient ("openAI")
     *
     * constructor injection becomes ambiguous because Spring no longer knows
     * which ChatClient should be injected.
     *
     * In that case, explicitly define the constructor and use @Qualifier on the
     * constructor parameter.
     *
     * Note:
     * Placing @Qualifier on the field does NOT work together with Lombok's
     * @RequiredArgsConstructor because Lombok does not copy the annotation to
     * the generated constructor parameter.
     */

    /*
    public AIService(@Qualifier("ollama") ChatClient chatClient) {
        this.chatClient = chatClient;
    }
    */


    public void getJoke() {

        // ---------------------------------------------------------------------
        // User Prompt
        // ---------------------------------------------------------------------
        //
        // Passing a String directly to prompt(...) is a shortcut for creating a
        // UserMessage.
        //
        // Internally this is equivalent to:
        //
        //      chatClient.prompt()
        //                .user("Give me a joke on programmers")
        //                .call()
        //                .content();
        //
        // Since no system prompt is provided, the model uses its default
        // behaviour to answer the user's request.
        //
        String content1 = chatClient.prompt("Give me a joke on programmers")
                .call()
                .content();

        System.out.println("User Prompt Only");
        System.out.println(content1);

        System.out.println("#####################");


        // ---------------------------------------------------------------------
        // System Prompt + User Prompt
        // ---------------------------------------------------------------------
        //
        // System Prompt
        //      Defines the assistant's behaviour, role, expertise and response
        //      style. It has higher priority than user prompts.
        //
        // User Prompt
        //      Specifies the actual task to be performed.
        //
        // Separating behavioural instructions into the system prompt keeps the
        // prompt cleaner and allows the application's personality to remain
        // consistent across different user requests.
        //
        String content2 = chatClient.prompt()
                .system("Act like a professional poet")
                .user("Write a poem in 4 lines on cats")
                .call()
                .content();

        System.out.println("User & System Prompt");
        System.out.println(content2);
    }
}