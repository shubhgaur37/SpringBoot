    /**
     * ChatClient is the primary abstraction provided by Spring AI for
     * interacting with Large Language Models (LLMs).
     *
     * It acts as a high-level client responsible for:
     *
     *      Application
     *            │
     *            ▼
     *      ChatClient
     *            │
     *            ▼
     *      ChatModel
     *            │
     *            ▼
     *      AI Provider
     *      (Ollama / OpenAI / Gemini / Anthropic ...)
     *
     * Since only a single ChatClient bean currently exists in the Spring
     * context, constructor injection generated by Lombok's
     * @RequiredArgsConstructor works without any additional configuration.
     */
    ChatClient chatClient;


